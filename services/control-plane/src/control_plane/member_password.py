def generate_initial_password() -> str:
    """``word-word-word-NNNN``;`secrets` RNG,词可重复,数字 0000-9999。"""
    words = "-".join(secrets.choice(_WORDS) for _ in range(3))
    return f"{words}-{secrets.randbelow(10000):04d}"
