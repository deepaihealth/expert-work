@dataclass(frozen=True)
class FactText:
    """一条事实在一种语言里的全部文字。"""

    topic: str  # 名词短语,能接在模板里
    x: str  # 旧值 / 主值
    y: str  # 新值 / 不同的值
    x_key: str  # 程序粗查用的关键串
    y_key: str
    state_x: str  # 用户自己把 X 说全(单独拿出来读得懂)
    state_y: str  # 用户自己把「改成 Y」说全
    short_y: str  # 离开上文读不懂的短更新
    ask: str  # 之后问起这件事
    memory_x: str  # 第三人称的记忆句
    memory_y: str
    asks: str  # 助手问「还是 X 吗」


@dataclass(frozen=True)
class Fact:
    key: str
    domain: str
    form: str
    texts: Mapping[str, FactText]
    #: §8.1 / §8.3:事故那条(健康 · 数值)—— B1 里按事故原样种(英文、置信度 0.8、无出处)。
    incident: bool = False


def _fact(
    key: str, domain: str, form: str, zh: FactText, en: FactText, *, incident: bool = False
) -> Fact:
    return Fact(key, domain, form, {"zh": zh, "en": en}, incident)


